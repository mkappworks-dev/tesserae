#!/usr/bin/env node
/*
 * Writes each Game's Templates from the approved mockup's builders (`structures.js`,
 * `structure-materials.js`): `mockup/templates/<game>.json`, which a test compares the declared
 * Templates against, and `games/<game>/src/templates.rs`, which declares them. Run it after
 * changing a builder or a style, from the checkout root: `node mockup/export-templates.mjs`.
 * `--check` writes nothing and fails if either output is out of date.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const context = vm.createContext({ document: { addEventListener() {} } });
for (const file of ["structure-materials.js", "structures.js"])
  vm.runInContext(readFileSync(join(root, "mockup", file), "utf8"), context, {
    filename: file,
  });
const { GAME_TEMPLATES, materialOf, spans } = vm.runInContext(
  "({ GAME_TEMPLATES, materialOf, spans })",
  context,
);

const SHAPES = {
  cube: "core:cube",
  slab: "core:slab",
  stair: "core:stair",
  post: "core:post",
  panel: "panel",
  table: "table",
};
/* Wilderness Structures stand on rougher ground than the Settlement levels for its Plots. */
const WILD_TOLERANCE_M = 2;
const KEEP = ".",
  AIR = ":",
  SYMBOLS =
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789#$%&*+=?@^~!<>/|;,";

/* The mockup turns a cell's +Z edge to -X per quarter; an orientation byte's quarter takes it to +X. */
const orientation = (turn) => (4 - (turn % 4)) % 4;

function exportTemplate(t) {
  const game = t.game.toLowerCase(),
    { cells } = t.build(),
    lo = [0, 1, 2].map((a) =>
      Math.min(...cells.map((c) => [c.x, c.y, c.z][a])),
    ),
    hi = [0, 1, 2].map((a) =>
      Math.max(...cells.map((c) => [c.x, c.y, c.z][a])),
    ),
    size = [0, 1, 2].map((a) => hi[a] - lo[a] + 1),
    palette = [
      { symbol: KEEP, cell: "keep" },
      { symbol: AIR, cell: "air" },
    ],
    symbolOf = new Map(),
    grid = Array.from({ length: size[1] }, () =>
      Array.from({ length: size[2] }, () => Array(size[0]).fill(KEEP)),
    );
  for (const c of cells) {
    let symbol = AIR;
    if (c.k !== "air") {
      const shape = SHAPES[c.shape];
      if (!shape) throw new Error(`${t.id}: no Shape for \`${c.shape}\``);
      const voxel = {
          material: materialOf(t, c),
          shape: shape.includes(":") ? shape : `${game}:${shape}`,
          orientation: orientation(c.turn || 0),
        },
        key = JSON.stringify(voxel);
      if (!symbolOf.has(key)) {
        if (symbolOf.size === SYMBOLS.length)
          throw new Error(`${t.id}: more cells than palette symbols`);
        symbolOf.set(key, SYMBOLS[symbolOf.size]);
        palette.push({ symbol: symbolOf.get(key), ...voxel });
      }
      symbol = symbolOf.get(key);
    }
    grid[c.y - lo[1]][c.z - lo[2]][c.x - lo[0]] = symbol;
  }
  return {
    name: `${game}:${t.id.split(":")[1].replace(/-/g, "_")}`,
    label: t.name,
    kind: t.kind,
    size,
    ground_layer: -lo[1],
    foundation: materialOf(t, { m: "base" }),
    level_tolerance_m: t.kind === "wild" ? WILD_TOLERANCE_M : null,
    spans: spans(t),
    palette,
    layers: grid.map((layer) => layer.map((row) => row.join(""))),
  };
}

const str = (s) => JSON.stringify(s);
function rust(game, templates) {
  const cell = (p) =>
    p.cell === "keep"
      ? "Keep"
      : p.cell === "air"
        ? "Air"
        : `Voxel(${str(p.material)}, ${str(p.shape)}, ${p.orientation})`;
  const drawn = templates
    .map(
      (t) => `    Drawn {
        name: ${str(t.name.split(":")[1])},
        ground_layer: ${t.ground_layer},
        foundation: ${str(t.foundation)},
        level_tolerance_m: ${t.level_tolerance_m === null ? "None" : `Some(${t.level_tolerance_m.toFixed(1)})`},
        spans: ${t.spans},
        palette: &[${t.palette.map((p) => `(${str(p.symbol).replace(/^"|"$/g, "'")}, ${cell(p)})`).join(", ")}],
        layers: &[${t.layers.map((l) => `&[${l.map(str).join(", ")}]`).join(", ")}],
    },`,
    )
    .join("\n");
  return `//! ${game[0].toUpperCase()}${game.slice(1)}'s Templates, written by \`node mockup/export-templates.mjs\` from the approved
//! mockup's builders. Edit those and run it again; do not edit this file.

use crate::tesserae::mods::content::{
    TemplateCell, TemplateDef, TemplatePaletteEntry, TemplateVoxel,
};

enum Cell {
    Keep,
    Air,
    Voxel(&'static str, &'static str, u8),
}
use Cell::*;

struct Drawn {
    name: &'static str,
    ground_layer: u32,
    foundation: &'static str,
    level_tolerance_m: Option<f32>,
    spans: bool,
    palette: &'static [(char, Cell)],
    layers: &'static [&'static [&'static str]],
}

const TEMPLATES: [Drawn; ${templates.length}] = [
${drawn}
];

pub fn templates() -> Vec<TemplateDef> {
    TEMPLATES
        .iter()
        .map(|t| TemplateDef {
            name: t.name.into(),
            cell_m: 1.0,
            palette: t
                .palette
                .iter()
                .map(|(symbol, cell)| TemplatePaletteEntry {
                    symbol: *symbol,
                    cell: match *cell {
                        Keep => TemplateCell::Keep,
                        Air => TemplateCell::Air,
                        Voxel(material, shape, orientation) => {
                            TemplateCell::Voxel(TemplateVoxel {
                                material: material.into(),
                                shape: Some(shape.into()),
                                orientation: Some(orientation),
                            })
                        }
                    },
                })
                .collect(),
            layers: t
                .layers
                .iter()
                .map(|layer| layer.iter().map(|&row| row.into()).collect())
                .collect(),
            ground_layer: Some(t.ground_layer),
            foundation: Some(t.foundation.into()),
            level_tolerance_m: t.level_tolerance_m,
            spans: t.spans,
        })
        .collect()
}
`;
}

let stale = [];
function emit(path, text) {
  const full = join(root, path);
  let old = null;
  try {
    old = readFileSync(full, "utf8");
  } catch {}
  if (old === text) return;
  if (check) stale.push(path);
  else {
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, text);
  }
}

for (const [Game, list] of Object.entries(GAME_TEMPLATES)) {
  const game = Game.toLowerCase(),
    templates = list.map(exportTemplate);
  emit(
    `mockup/templates/${game}.json`,
    JSON.stringify({ game, templates }, null, 1) + "\n",
  );
  const formatted = execFileSync(
    "rustfmt",
    ["--edition", "2024", "--config", "max_width=100", "--emit", "stdout"],
    { input: rust(game, templates), encoding: "utf8" },
  );
  emit(`games/${game}/src/templates.rs`, formatted);
}
if (stale.length) {
  console.error(
    `out of date, run node mockup/export-templates.mjs: ${stale.join(", ")}`,
  );
  process.exit(1);
}
console.log(
  check ? "Templates are up to date" : "wrote every Game's Templates",
);
